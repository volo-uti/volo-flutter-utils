// Writes the volo_flutter_utils API index into the product's AGENTS.md so coding agents
// find existing widgets instead of building look-alikes.
//
//   dart run volo_flutter_utils:agent_index           write or update the block
//   dart run volo_flutter_utils:agent_index --check   exit 1 when it is missing or stale
//
// The lines come from the package's shipped `doc/index.txt`; no analyzer is
// needed here.
import 'dart:io';
import 'dart:isolate';

const _name = 'volo_flutter_utils';
const _begin = '<!-- BEGIN:volo-flutter-utils-index -->';
const _end = '<!-- END:volo-flutter-utils-index -->';

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  final uri = await Isolate.resolvePackageUri(
    Uri.parse('package:$_name/$_name.dart'),
  );
  if (uri == null) {
    stderr.writeln('Cannot locate package:$_name. Run `pub get` first.');
    exit(1);
  }
  // .../<package root>/lib/volo_flutter_utils.dart -> <package root>
  final root = File.fromUri(uri).parent.parent;
  final indexFile = File('${root.path}/doc/index.txt');
  if (!indexFile.existsSync()) {
    stderr.writeln('$_name has no doc/index.txt; update the package.');
    exit(1);
  }
  final lines = indexFile.readAsStringSync().trimRight();
  final block = [
    _begin,
    '## $_name index',
    '',
    [
      'Generated by `dart run $_name:agent_index`; do not edit by hand. Each',
      "entry's doc is doc/<section>/<name>.md relative to the $_name package",
      'root (`[.]` is the doc folder itself; find the root as `rootUri` of',
      '`$_name` in `.dart_tool/package_config.json`). Before writing code,',
      'find the helper here and read its doc. Use these instead of',
      'writing new look-alikes. If nothing fits, say what you',
      'looked for first. Other public classes, enums, styles and data classes in each folder are listed in its doc file.',
    ].join(' '),
    '',
    '```text',
    lines,
    '```',
    _end,
  ].join('\n');

  final agents = File('AGENTS.md');
  final text = agents.existsSync() ? agents.readAsStringSync() : '';
  final begin = text.indexOf(_begin);
  final end = text.indexOf(_end);
  final has = begin >= 0 && end > begin;
  final current = has ? text.substring(begin, end + _end.length) : null;

  if (check) {
    if (current != block) {
      stderr.writeln(
        'AGENTS.md $_name index is ${has ? 'stale' : 'missing'}: '
        'run `dart run $_name:agent_index`.',
      );
      exit(1);
    }
    return;
  }
  final updated = has
      ? text.replaceRange(begin, end + _end.length, block)
      : '${text.trimRight()}${text.trim().isEmpty ? '' : '\n\n'}$block\n';
  if (updated != text) agents.writeAsStringSync(updated);
  stdout.writeln(
    'AGENTS.md: $_name index ${current == block ? 'is current' : 'written'}.',
  );
}
