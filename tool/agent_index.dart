// Generates the public API index of volo_flutter_utils:
//   - the managed blocks in AGENTS.md (read by agents working in this repo),
//   - doc/index.txt (shipped to products, see
//     `dart run volo_flutter_utils:agent_index`).
//
// `dart run tool/agent_index.dart` writes them; `--check` exits 1 when one is
// stale, when a public declaration has no doc sentence, when a first sentence
// is over 90 characters, when a block is over the size limit, or when a file
// under lib/src is not exported from the barrel (it would never be indexed). The one-line
// index comes from each declaration's `///` first sentence, so those sentences
// are the contract.
import 'dart:io';

import 'src/api.dart';

const maxBlockChars = 8000;

/// Longest allowed first sentence of an indexed declaration, final period
/// included.
const maxSentenceChars = 90;

String beginMarker(Pkg p) => '<!-- BEGIN:${p.indexId} -->';
String endMarker(Pkg p) => '<!-- END:${p.indexId} -->';

/// One index line for [g]: `v_button|VButton: Sentence.`; the doc is
/// `doc/<section>/<name>.md`, with the section on the `[section]` line above.
/// Only one declaration is described: the first main widget of a component
/// folder, or the one named like the source file (else the first).
String indexLine(Group g) {
  final name = g.key.split('/').last;
  final mains = g.mains;
  final ApiDecl d;
  if (mains.isNotEmpty) {
    d = mains.first;
  } else {
    final flat = name.replaceAll('_', '');
    d = g.decls.firstWhere(
      (x) => x.name.toLowerCase() == flat,
      orElse: () => g.decls.first,
    );
  }
  return '$name|${d.name}: ${indexSentence(d.docText)}';
}

/// Index lines of [groups]: a `[section]` heading per doc folder (`[.]` for
/// the package's own doc folder), then one [indexLine] per doc file.
List<String> indexLines(List<Group> groups) {
  final lines = <String>[];
  String? section;
  for (final g in groups) {
    final i = g.key.lastIndexOf('/');
    final s = i < 0 ? '.' : g.key.substring(0, i);
    if (s != section) lines.add('[${section = s}]');
    lines.add(indexLine(g));
  }
  return lines;
}

String renderBlock(Pkg p, List<String> lines) => [
  beginMarker(p),
  '## ${p.name} index',
  '',
  [
    'Generated by `make index` from the first sentence of each public',
    "declaration's doc comment; do not edit by hand. Before using a ${p.name}",
    "API, find it here and read its doc file. Each entry's doc is",
    '`doc/<section>/<name>.md` (`[.]` is the doc folder itself).',
    'Other public classes, enums, styles and data classes in each folder are listed in its doc file. If nothing',
    'fits, say what you looked for first.',
  ].join(' '),
  '',
  '```text',
  ...lines,
  '```',
  endMarker(p),
].join('\n');

String applyBlock(String agents, Pkg p, String block) {
  final begin = agents.indexOf(beginMarker(p));
  final end = agents.indexOf(endMarker(p));
  if (begin >= 0 && end > begin) {
    return agents.replaceRange(begin, end + endMarker(p).length, block);
  }
  return '${agents.trimRight()}\n\n$block\n';
}

String? currentBlock(String agents, Pkg p) {
  final begin = agents.indexOf(beginMarker(p));
  final end = agents.indexOf(endMarker(p));
  return begin >= 0 && end > begin
      ? agents.substring(begin, end + endMarker(p).length)
      : null;
}

Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  final problems = <String>[];
  final agentsFile = File('$repoRoot/AGENTS.md');
  var agents = agentsFile.existsSync() ? agentsFile.readAsStringSync() : '';

  for (final pkg in packages) {
    for (final file in unexportedSources(pkg)) {
      problems.add(
        '$file is not exported from lib/${pkg.name}.dart: add an export line '
        'for it, or move its code into an exported file',
      );
    }
    final decls = await loadApi(pkg);
    for (final d in decls) {
      if (d.sentence.isEmpty) {
        problems.add('${d.location}: missing doc sentence');
      } else if (d.sentence.length > maxSentenceChars) {
        problems.add(
          '${d.location} (${d.sentence.length} chars): first sentence over '
          '$maxSentenceChars, move detail to the second sentence',
        );
      }
    }
    final lines = indexLines(groupsOf(pkg, decls));
    final block = renderBlock(pkg, lines);
    if (block.length > maxBlockChars) {
      problems.add(
        '${pkg.name} index block is ${block.length} chars (limit $maxBlockChars): shorten doc sentences',
      );
    }

    final indexFile = File('$repoRoot/doc/index.txt');
    final indexText = '${lines.join('\n')}\n';
    if (check) {
      if (!indexFile.existsSync() ||
          indexFile.readAsStringSync() != indexText) {
        problems.add('doc/index.txt is stale: run make index');
      }
      if (currentBlock(agents, pkg) != block) {
        problems.add(
          'AGENTS.md ${pkg.name} index block is stale: run make index',
        );
      }
    } else {
      indexFile.parent.createSync(recursive: true);
      indexFile.writeAsStringSync(indexText);
      agents = applyBlock(agents, pkg, block);
      stdout.writeln(
        '${pkg.name}: ${lines.length} lines, block ${block.length} chars',
      );
    }
  }

  if (!check) agentsFile.writeAsStringSync(agents);
  if (problems.isNotEmpty) {
    problems.forEach(stderr.writeln);
    exit(1);
  }
}
